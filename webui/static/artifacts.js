/**
 * Artifacts & Visual Canvas Panel for Antigravity (AGY) WebUI
 * Conforms to .gemini/rules/webui_design_system.md
 */

let _artifactsData = [];
let _selectedArtifact = null;
let _artifactFilter = 'all';

async function loadArtifacts(force = false) {
  const listEl = document.getElementById('artifactList');
  if (!listEl) return;

  try {
    const sessionId = (typeof S !== 'undefined' && S && S.session && S.session.session_id) || '';
    const res = await fetch(`/api/artifacts?session_id=${encodeURIComponent(sessionId)}`);
    if (!res.ok) throw new Error(`HTTP ${res.status}`);
    const data = await res.json();
    _artifactsData = data.artifacts || [];
    renderArtifactsSidebar();
    
    // Auto-select first artifact if none selected
    if (_artifactsData.length > 0 && !_selectedArtifact) {
      selectArtifactByIndex(0);
    }
  } catch (err) {
    if (listEl) {
      listEl.innerHTML = `<div style="padding:16px;color:var(--muted);font-size:12px">Unable to load artifacts (${escapeHtml(err.message)}).</div>`;
    }
  }
}

function setArtifactFilter(kind) {
  _artifactFilter = kind;
  const buttons = document.querySelectorAll('.artifact-cat-btn');
  buttons.forEach(btn => {
    btn.classList.toggle('active', btn.dataset.kind === kind);
  });
  renderArtifactsSidebar();
}

function renderArtifactsSidebar() {
  const listEl = document.getElementById('artifactList');
  const countEl = document.getElementById('artifactTotalCount');
  const searchInput = document.getElementById('artifactSearchInput');
  if (!listEl) return;

  const query = (searchInput ? searchInput.value : '').trim().toLowerCase();
  
  const filtered = _artifactsData.filter(a => {
    if (_artifactFilter !== 'all' && a.kind !== _artifactFilter) return false;
    if (query && !a.name.toLowerCase().includes(query) && !a.relative_path.toLowerCase().includes(query)) return false;
    return true;
  });

  if (countEl) countEl.textContent = String(filtered.length);

  if (filtered.length === 0) {
    listEl.innerHTML = `
      <div class="mcp-empty-list">
        <div style="font-weight:600;margin-bottom:4px;color:var(--text)">No Artifacts Found</div>
        <div style="font-size:11.5px;color:var(--muted)">Reports, diagrams, and scratch files generated by AGY will appear here.</div>
      </div>
    `;
    return;
  }

  listEl.innerHTML = filtered.map((art, idx) => {
    const isSelected = _selectedArtifact && _selectedArtifact.absolute_path === art.absolute_path;
    const sizeKb = (art.size_bytes / 1024).toFixed(1);
    
    let kindBadgeClass = 'pill-surface';
    if (art.kind === 'markdown') kindBadgeClass = 'pill-gold';
    else if (art.kind === 'image') kindBadgeClass = 'pill-blue';
    else if (art.kind === 'code') kindBadgeClass = 'pill-green';

    return `
      <div class="mcp-server-card ${isSelected ? 'selected' : ''}" onclick="selectArtifactByPath('${escapeHtml(art.absolute_path)}')">
        <div class="mcp-server-card-top">
          <svg width="14" height="14" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true"><path d="M14 2H6a2 2 0 0 0-2 2v16a2 2 0 0 0 2 2h12a2 2 0 0 0 2-2V8z"/><polyline points="14 2 14 8 20 8"/></svg>
          <strong style="font-size:12.5px;color:var(--text);overflow:hidden;text-overflow:ellipsis;white-space:nowrap;">${escapeHtml(art.name)}</strong>
        </div>
        <div style="font-size:11px;color:var(--muted);font-family:var(--font-mono);overflow:hidden;text-overflow:ellipsis;white-space:nowrap;">${escapeHtml(art.relative_path)}</div>
        <div style="display:flex;align-items:center;gap:6px;margin-top:2px;">
          <span class="swarm-node-pill ${kindBadgeClass}">${escapeHtml(art.kind)}</span>
          <span style="font-size:10.5px;color:var(--muted);font-family:var(--font-mono);">${sizeKb} KB</span>
          ${art.is_scratch ? '<span class="swarm-node-pill pill-surface">scratch</span>' : ''}
        </div>
      </div>
    `;
  }).join('');
}

function selectArtifactByIndex(idx) {
  if (_artifactsData && _artifactsData[idx]) {
    selectArtifactByPath(_artifactsData[idx].absolute_path);
  }
}

async function selectArtifactByPath(path) {
  const art = _artifactsData.find(a => a.absolute_path === path);
  if (!art) return;
  _selectedArtifact = art;
  renderArtifactsSidebar();
  
  const titleEl = document.getElementById('artifactDetailTitle');
  const pathEl = document.getElementById('artifactDetailPath');
  const sizeEl = document.getElementById('artifactDetailSize');
  const badgeEl = document.getElementById('artifactDetailBadge');
  const bodyEl = document.getElementById('artifactCanvasBody');
  const emptyEl = document.getElementById('artifactDetailEmpty');

  if (emptyEl) emptyEl.style.display = 'none';
  if (bodyEl) bodyEl.style.display = 'block';

  if (titleEl) titleEl.textContent = art.name;
  if (pathEl) pathEl.textContent = art.absolute_path;
  if (sizeEl) sizeEl.textContent = `${(art.size_bytes / 1024).toFixed(1)} KB`;
  if (badgeEl) badgeEl.textContent = art.kind.toUpperCase();

  if (bodyEl) {
    bodyEl.innerHTML = '<div style="padding:24px;color:var(--muted);font-size:12px;">Loading artifact canvas...</div>';
  }

  try {
    const res = await fetch(`/api/artifacts/content?path=${encodeURIComponent(art.absolute_path)}`);
    if (!res.ok) throw new Error(`HTTP ${res.status}`);
    const data = await res.json();
    renderArtifactCanvas(data, art);
  } catch (err) {
    if (bodyEl) {
      bodyEl.innerHTML = `<div style="padding:24px;color:var(--error);font-size:12.5px;">Error loading artifact: ${escapeHtml(err.message)}</div>`;
    }
  }
}

function renderArtifactCanvas(data, art) {
  const bodyEl = document.getElementById('artifactCanvasBody');
  if (!bodyEl) return;

  if (data.is_binary && data.data_url) {
    bodyEl.innerHTML = `
      <div class="artifact-media-view">
        <img src="${data.data_url}" alt="${escapeHtml(art.name)}" class="artifact-image-preview" />
      </div>
    `;
    return;
  }

  const content = data.content || '';
  
  if (art.kind === 'markdown') {
    let rendered = '';
    if (typeof marked !== 'undefined') {
      rendered = marked.parse(content);
    } else if (typeof renderMarkdownProse === 'function') {
      rendered = renderMarkdownProse(content);
    } else {
      rendered = `<pre class="artifact-code-pre"><code>${escapeHtml(content)}</code></pre>`;
    }
    
    bodyEl.innerHTML = `
      <div class="artifact-markdown-canvas">
        <div class="artifact-prose-wrap msg-body">
          ${rendered}
        </div>
      </div>
    `;
  } else {
    // Code / Plain Text / JSON View
    bodyEl.innerHTML = `
      <div class="artifact-code-canvas">
        <pre class="artifact-code-pre"><code>${escapeHtml(content)}</code></pre>
      </div>
    `;
  }
}

function copyArtifactContent() {
  if (!_selectedArtifact) return;
  fetch(`/api/artifacts/content?path=${encodeURIComponent(_selectedArtifact.absolute_path)}`)
    .then(r => r.json())
    .then(d => {
      if (d.content) {
        navigator.clipboard.writeText(d.content).then(() => {
          const btn = document.getElementById('btnCopyArtifact');
          if (btn) {
            const orig = btn.textContent;
            btn.textContent = 'Copied!';
            setTimeout(() => { btn.textContent = orig; }, 1500);
          }
        });
      }
    });
}

function downloadArtifact() {
  if (!_selectedArtifact) return;
  fetch(`/api/artifacts/content?path=${encodeURIComponent(_selectedArtifact.absolute_path)}`)
    .then(r => r.json())
    .then(d => {
      let blob;
      if (d.is_binary && d.data_url) {
        const byteString = atob(d.data_url.split(',')[1]);
        const ab = new ArrayBuffer(byteString.length);
        const ia = new Uint8Array(ab);
        for (let i = 0; i < byteString.length; i++) ia[i] = byteString.charCodeAt(i);
        blob = new Blob([ab], { type: d.mime_type || 'application/octet-stream' });
      } else {
        blob = new Blob([d.content || ''], { type: 'text/plain;charset=utf-8' });
      }
      const url = URL.createObjectURL(blob);
      const a = document.createElement('a');
      a.href = url;
      a.download = _selectedArtifact.name;
      document.body.appendChild(a);
      a.click();
      document.body.removeChild(a);
      URL.revokeObjectURL(url);
    });
}

function escapeHtml(str) {
  if (typeof str !== 'string') return String(str || '');
  return str.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;').replace(/'/g, '&#039;');
}
